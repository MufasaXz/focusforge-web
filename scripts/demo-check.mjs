import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const base = process.env.TEST_URL || 'http://localhost:4173';
const hidden = async value => page.evaluate(value => { Object.defineProperty(document, 'hidden', { configurable: true, value }); document.dispatchEvent(new Event('visibilitychange')); }, value);
const seconds = time => time.split(':').reduce((a,b) => Number(a)*60+Number(b));
try {
  await page.goto(base);
  await page.waitForFunction(() => [...document.querySelectorAll('.feature-phone img')].every(img => img.dataset.decoded === 'true'));
  assert.equal(await page.locator('.phone-front').getAttribute('data-face'), 'Retro');
  const initial = await page.locator('.clock-a11y').textContent();
  const hand = await page.locator('.retro-hand').getAttribute('data-angle');
  await page.waitForFunction(angle => document.querySelector('.retro-hand').getAttribute('data-angle') !== angle, hand, { timeout: 3500 });
  assert.notEqual(await page.locator('.retro-hand').getAttribute('data-angle'), hand);
  const synchronized = await page.locator('.retro-hand').getAttribute('data-angle');
  assert.ok(Math.abs(Number(synchronized) - (1500 - seconds(await page.locator('.clock-a11y').textContent())) / 1500 * 360) < .00001);
  assert.equal(await page.locator('.phone-front').getAttribute('data-face'), 'Retro');
  await page.waitForFunction(() => document.querySelector('.phone-front').dataset.face === 'Flip');
  await page.waitForTimeout(650);
  assert.ok(1500 - seconds(await page.locator('.clock-a11y').textContent()) >= 5);
  assert.ok(seconds(initial) > seconds(await page.locator('.clock-a11y').textContent()));
  assert.equal(await page.locator('.hero-face-flip').evaluate(el => getComputedStyle(el).opacity), '1');
  await page.waitForFunction(() => document.querySelector('.demo-flip-card:last-child').getAnimations({ subtree: true }).some(animation => animation.playState === 'running'));
  assert.equal(await page.locator('.demo-flip-card').count(), 4);
  await page.screenshot({ path: '/tmp/focusforge-web-review/clock-flip.png' });
  await page.waitForFunction(() => document.querySelector('.phone-front').dataset.face === 'Minimal');
  const time = await page.locator('.clock-a11y').textContent();
  await hidden(true);
  await page.waitForTimeout(2400);
  assert.equal(await page.locator('.clock-a11y').textContent(), time);
  await hidden(false);
  await page.waitForFunction(t => document.querySelector('.clock-a11y').textContent !== t, time);
  assert.equal(await page.locator('.phone-front').getAttribute('data-face'), 'Minimal');
  assert.ok(seconds(time)-seconds(await page.locator('.clock-a11y').textContent()) >= 2);
  await page.locator('.podium').scrollIntoViewIfNeeded();
  await page.getByRole('button', { name: 'Replay podium' }).click();
  const inspect = () => page.locator('.podium-column').first().evaluate(el => {
    const matrix = selector => new DOMMatrix(getComputedStyle(el.querySelector(selector)).transform).m22;
    return { rise: matrix('.podium-outline'), fill: matrix('.podium-fill'), medal: getComputedStyle(el.querySelector('.podium-medal')).opacity, weight: getComputedStyle(el.querySelector('.podium-name')).fontWeight };
  });
  await page.waitForTimeout(400);
  const rising = await inspect();
  assert.ok(rising.rise > 0 && rising.rise < 1); assert.equal(rising.fill, 0); assert.equal(rising.medal, '0'); assert.equal(rising.weight, '400');
  await page.waitForTimeout(1100);
  const filling = await inspect();
  assert.equal(filling.rise, 1); assert.ok(filling.fill > 0 && filling.fill < 1); assert.equal(filling.medal, '0');
  await page.waitForTimeout(1200);
  const filled = await inspect();
  assert.equal(filled.fill, 1); assert.equal(filled.medal, '1'); assert.ok(Number(filled.weight) >= 699);
  assert.deepEqual(await page.locator('.podium-name').allTextContents(), ['Keshab', 'Sudeep', 'Pranshu']);
  await page.screenshot({ path: '/tmp/focusforge-web-review/community-final.png' });
  await page.getByRole('button', { name: 'Replay podium' }).click();
  await page.waitForTimeout(250);
  await hidden(true);
  await page.locator('.podium-outline').first().evaluate(async el => { await el.getAnimations()[0].ready; });
  const pause = await page.locator('.podium-outline').first().evaluate(el => el.getAnimations()[0].currentTime);
  await page.waitForTimeout(400);
  assert.equal(await page.locator('.podium-outline').first().evaluate(el => el.getAnimations()[0].currentTime), pause);
  await hidden(false);
  await page.locator('.friends-art').scrollIntoViewIfNeeded();
  const timers = await page.locator('.friend-timer').allTextContents();
  await page.waitForTimeout(1200);
  assert.notDeepEqual((await page.locator('.friend-timer').allTextContents()).slice(0,3), timers.slice(0,3));
  assert.equal((await page.locator('.friend-timer').allTextContents())[3], timers[3]);
  const before = await page.locator('.friend-timer [role=timer]').first().textContent();
  await hidden(true); await page.waitForTimeout(2200);
  assert.equal(await page.locator('.friend-timer [role=timer]').first().textContent(), before);
  await hidden(false);
  await page.waitForTimeout(100);
  assert.ok(seconds(await page.locator('.friend-timer [role=timer]').first().textContent()) - seconds(before) >= 2);
  await page.evaluate(() => window.scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' }));
  await page.waitForTimeout(100);
  const offscreen = await page.locator('.friend-timer [role=timer]').first().textContent();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator('.friend-timer [role=timer]').first().textContent(), offscreen);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('.phone-front').getAttribute('data-face'), 'Retro');
  const reduced = await page.locator('.clock-a11y').textContent();
  await page.waitForTimeout(1200);
  assert.notEqual(await page.locator('.clock-a11y').textContent(), reduced);
  await page.locator('.podium').scrollIntoViewIfNeeded();
  assert.equal((await inspect()).fill, 1);
  assert.equal((await inspect()).medal, '1');
  assert.deepEqual(errors, []);
  console.log('PASS: decoded launcher images; Retro hand, 5s face cycle, continuous countdown, hidden catch-up; podium rise then fill then bold/medals, replay and pause; four varied timers with inactive friend, hidden/offscreen pause; reduced-motion Retro and final podium.');
} finally { await browser.close(); }
